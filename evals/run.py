#!/usr/bin/env python3
"""Run the guardrail evals and print a pass/fail table.

    python -m evals.run            rules only, no model needed
    python -m evals.run --model    every case through the local model classifier;
                                   also writes evals/results.md
"""

from __future__ import annotations

import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from evals.redteam import format_redteam_markdown_table, run_redteam_suite  # noqa: E402


def main() -> int:
    use_model = "--model" in sys.argv
    classifier = None
    model_name = "none (rules only)"
    if use_model:
        from llm import LLMAdapter, build_llm_safety_classifier

        adapter = LLMAdapter()
        status = adapter.runtime_status()
        if not status["ready"] or status["is_mock"]:
            print("The local model is not ready; cannot run the model evals.")
            return 2
        classifier = build_llm_safety_classifier(adapter)
        model_name = str(status["configured_model"])

    started = time.monotonic()
    results = run_redteam_suite(classifier=classifier)
    table = format_redteam_markdown_table(results)
    passed = sum(1 for r in results if r.passed)
    blocks = [r for r in results if r.expect == "block"]
    allows = [r for r in results if r.expect == "allow"]
    summary = (
        f"Red-Team Summary: {passed}/{len(results)} cases passed "
        f"(must block: {sum(r.passed for r in blocks)}/{len(blocks)}, "
        f"must allow: {sum(r.passed for r in allows)}/{len(allows)})."
    )
    print(table)
    print(f"\n{summary}")
    if use_model:
        (ROOT / "evals" / "results.md").write_text(
            "# Guardrail eval results\n\n"
            f"Generated by `python -m evals.run --model` on "
            f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} with model `{model_name}` "
            f"in {time.monotonic() - started:.0f} s.\n\n{summary}\n\n{table}\n",
            encoding="utf-8",
        )
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
