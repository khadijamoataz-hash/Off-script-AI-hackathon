#!/usr/bin/env python3
"""Run the guardrail evals and print a pass/fail table.

    python -m evals.run            rules only, no model needed
    python -m evals.run --model    every case through the local model classifier;
                                   also writes evals/results.md
    python -m evals.run --model --repeat 3
                                   the whole suite 3 times, to measure how stable the
                                   model's answers are; results.md reports every run
"""

from __future__ import annotations

import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from evals.redteam import format_redteam_markdown_table, run_redteam_suite  # noqa: E402


def main() -> int:
    use_model = "--model" in sys.argv
    classifier = None
    model_name = "none (rules only)"
    if use_model:
        from llm import LLMAdapter, build_llm_safety_classifier

        adapter = LLMAdapter()
        status = adapter.runtime_status()
        if not status["ready"] or status["is_mock"]:
            print("The local model is not ready; cannot run the model evals.")
            return 2
        classifier = build_llm_safety_classifier(adapter)
        model_name = str(status["configured_model"])

    repeat = 1
    if "--repeat" in sys.argv:
        repeat = max(1, int(sys.argv[sys.argv.index("--repeat") + 1]))
        if not use_model:
            repeat = 1  # the rules are deterministic; repeating them measures nothing

    started = time.monotonic()
    runs = [run_redteam_suite(classifier=classifier) for _ in range(repeat)]
    summaries = [_summary(results) for results in runs]
    results = runs[-1]
    table = format_redteam_markdown_table(results)
    passed_every_run = all(r.passed for results_ in runs for r in results_)
    for i, summary in enumerate(summaries, 1):
        print(f"Run {i} of {repeat}: {summary}" if repeat > 1 else summary)
    print(table)
    unstable = _unstable_cases(runs)
    if unstable:
        print("\nCases that failed in at least one run:")
        print(unstable)
    if use_model:
        runs_text = "\n".join(
            f"- Run {i}: {summary}" for i, summary in enumerate(summaries, 1)
        )
        header = (
            f"Generated by `python -m evals.run --model{f' --repeat {repeat}' if repeat > 1 else ''}` on "
            f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} with model `{model_name}` "
            f"in {time.monotonic() - started:.0f} s.\n\n"
        )
        if repeat > 1:
            body = (
                f"The suite was run {repeat} times in a row, because a local model can answer "
                "the same text differently from one run to the next.\n\n"
                f"{runs_text}\n\n"
                + (
                    "Cases that failed in at least one run:\n\n" + unstable + "\n\n"
                    if unstable
                    else "Every case gave the expected result in every run.\n\n"
                )
                + f"Table of the last run:\n\n{table}\n"
            )
        else:
            body = f"{summaries[0]}\n\n{table}\n"
        (ROOT / "evals" / "results.md").write_text(
            "# Guardrail eval results\n\n" + header + body, encoding="utf-8"
        )
    return 0 if passed_every_run else 1


def _summary(results) -> str:
    passed = sum(1 for r in results if r.passed)
    blocks = [r for r in results if r.expect == "block"]
    allows = [r for r in results if r.expect == "allow"]
    return (
        f"Red-Team Summary: {passed}/{len(results)} cases passed "
        f"(must block: {sum(r.passed for r in blocks)}/{len(blocks)}, "
        f"must allow: {sum(r.passed for r in allows)}/{len(allows)})."
    )


def _unstable_cases(runs) -> str:
    """Markdown table of cases that failed in at least one run, with their pass count."""
    rows = []
    for i, first in enumerate(runs[0]):
        outcomes = [results[i] for results in runs]
        fails = [r for r in outcomes if not r.passed]
        if fails:
            rows.append(
                f"| `{first.case_id}` | {first.name} | {first.expect} | "
                f"{len(outcomes) - len(fails)} of {len(outcomes)} | `{fails[0].actual_category.value}` |"
            )
    if not rows:
        return ""
    return "| Case | What it tries | Expected | Runs passed | Category when it failed |\n|---|---|---|---|---|\n" + "\n".join(rows)


if __name__ == "__main__":
    raise SystemExit(main())
