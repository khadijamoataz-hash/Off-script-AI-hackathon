"""Strategist agent: Lean Canvas, riskiest assumption, demand-test plan, landing page copy.

The landing page itself is rendered by code from the typed fields below, so it has fixed
placeholder slots instead of testimonials, and no counters, prices or deadlines.
"""

from __future__ import annotations

import html
import re

from pydantic import BaseModel, Field, field_validator

from agents import AgentResult, run_agent
from agents.intake import FounderBrief
from agents.researcher import Opportunity, format_sources
from evidence import FetchedPage
from llm import LLMAdapter

CANVAS_BOXES: tuple[tuple[str, str], ...] = (
    ("problem", "Problem"),
    ("customer_segments", "Customer segments"),
    ("unique_value_proposition", "Unique value proposition"),
    ("solution", "Solution"),
    ("channels", "Channels"),
    ("revenue_streams", "Revenue streams"),
    ("cost_structure", "Cost structure"),
    ("key_metrics", "Key metrics"),
    ("unfair_advantage", "Unfair advantage"),
)

TESTIMONIAL_SLOT = "[Real customer quote - collect after launch]"
FORM_SLOT = "[YOUR-FORM-URL]"


class CanvasBox(BaseModel):
    text: str = Field(min_length=3, max_length=400)
    source_number: int | None = None
    quote: str | None = Field(default=None, max_length=600)


class LeanCanvas(BaseModel):
    problem: CanvasBox
    customer_segments: CanvasBox
    unique_value_proposition: CanvasBox
    solution: CanvasBox
    channels: CanvasBox
    revenue_streams: CanvasBox
    cost_structure: CanvasBox
    key_metrics: CanvasBox
    unfair_advantage: CanvasBox


def _plain(text: str) -> str:
    if re.search(r"#\w", text):
        raise ValueError("Remove all hashtags.")
    if re.search(r"[\U0001F300-\U0001FAFF☀-➿]", text):
        raise ValueError("Remove all emoji.")
    return text


class LandingCopy(BaseModel):
    headline: str = Field(min_length=5, max_length=120)
    subheadline: str = Field(min_length=10, max_length=300)
    points: list[str] = Field(min_length=3, max_length=3)
    who_it_is_for: str = Field(min_length=10, max_length=300)
    cta_label: str = Field(min_length=3, max_length=40)

    @field_validator("headline", "subheadline", "who_it_is_for", "cta_label")
    @classmethod
    def plain(cls, text: str) -> str:
        return _plain(text)


class StrategyOutput(BaseModel):
    canvas: LeanCanvas
    riskiest_assumption: str = Field(min_length=10, max_length=500)
    test_plan: str = Field(min_length=20, max_length=800)
    landing: LandingCopy
    invite_post: str = Field(min_length=40, max_length=900)

    @field_validator("invite_post")
    @classmethod
    def plain_post(cls, text: str) -> str:
        return _plain(text)


def design_business(
    adapter: LLMAdapter,
    brief: FounderBrief,
    option: Opportunity,
    critic_risks: list[str],
    pages: list[FetchedPage],
    excerpts: list[str],
    verified: list[tuple[int, str]] | None = None,
) -> AgentResult[StrategyOutput]:
    risks = "\n".join(f"- {risk}" for risk in critic_risks) or "- (none recorded)"
    quotes = "\n".join(f"[{number}] {quote}" for number, quote in verified or [])
    user_prompt = (
        f"{brief.as_prompt()}\n\n"
        "APPROVED OPTION\n"
        f"Title: {option.title}\nCustomer: {option.customer}\n"
        f"Problem: {option.problem}\nProduct: {option.product}\n\n"
        f"CRITIC'S RISKS\n{risks}\n\n"
        + (f"VERIFIED QUOTES (checked word for word against the numbered source)\n{quotes}\n\n" if quotes else "")
        + format_sources(pages, excerpts)
    )
    return run_agent(
        adapter, prompt_name="strategist", user_prompt=user_prompt, response_model=StrategyOutput
    )


def render_landing_page(copy: LandingCopy) -> str:
    """A small self-contained HTML page. The form posts nowhere until the founder adds their
    own form service; Foundry collects no sign-ups itself."""
    e = html.escape
    points = "\n".join(f"      <li>{e(point)}</li>" for point in copy.points)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(copy.headline)}</title>
<!-- DRAFT generated by Foundry for the founder to review. Not published by Foundry.
     Replace {FORM_SLOT} with your own form service before you publish it. -->
<style>
  body{{font-family:system-ui,-apple-system,"Segoe UI",sans-serif;margin:0;color:#16181d;background:#f7f6fc;line-height:1.55}}
  main{{max-width:640px;margin:0 auto;padding:48px 20px}}
  h1{{font-size:2rem;line-height:1.2;margin:0 0 12px}}
  .sub{{font-size:1.1rem;color:#4a4f5c;margin:0 0 24px}}
  ul{{padding-left:20px;margin:0 0 24px}} li{{margin:6px 0}}
  form{{display:flex;gap:8px;flex-wrap:wrap;margin:24px 0}}
  input{{flex:1;min-width:200px;padding:12px;border:1px solid #c9c6d8;border-radius:10px;font:inherit}}
  button{{padding:12px 18px;border:0;border-radius:10px;background:#6847f5;color:#fff;font:inherit;font-weight:600}}
  .slot{{border:1px dashed #c9c6d8;border-radius:10px;padding:12px;color:#77758b;font-size:.95rem}}
</style>
</head>
<body>
<main>
  <h1>{e(copy.headline)}</h1>
  <p class="sub">{e(copy.subheadline)}</p>
  <ul>
{points}
  </ul>
  <p><strong>Who it is for:</strong> {e(copy.who_it_is_for)}</p>
  <form action="{FORM_SLOT}" method="post">
    <label for="email" hidden>Email</label>
    <input id="email" name="email" type="email" placeholder="you@example.com" required>
    <button type="submit">{e(copy.cta_label)}</button>
  </form>
  <p class="slot">{TESTIMONIAL_SLOT}</p>
</main>
</body>
</html>
"""
